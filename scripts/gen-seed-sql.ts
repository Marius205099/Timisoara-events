/** Regenerates supabase/migrations/*_seed.sql from the TypeScript taxonomy, sources and venue registry. */
import fs from "node:fs";
import { AGE_GROUPS, CATEGORIES } from "../src/lib/taxonomy";
import { KNOWN_VENUES } from "../src/ingestion/known-venues";
import { SOURCES } from "../src/ingestion/sources";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const lines: string[] = ["-- Generated by scripts/gen-seed-sql.ts — do not edit by hand.", ""];

lines.push("insert into categories (id, label, sort) values");
lines.push(CATEGORIES.map((c, i) => `  (${q(c.id)}, ${q(c.label)}, ${i})`).join(",\n") + "\non conflict (id) do update set label = excluded.label, sort = excluded.sort;\n");

lines.push("insert into age_groups (id, label, min_age, max_age, sort) values");
lines.push(AGE_GROUPS.map((a, i) => `  (${q(a.id)}, ${q(a.label)}, ${a.min}, ${a.max}, ${i})`).join(",\n") + "\non conflict (id) do update set label = excluded.label;\n");

lines.push("insert into sources (id, name, homepage, adapter, config, enabled, auto_publish, access_notes) values");
lines.push(
  SOURCES.map((s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.homepage)}, ${q(s.adapter)}, ${q(JSON.stringify(s.config))}::jsonb, ${s.enabled}, ${s.autoPublish}, ${q(s.accessNotes)})`).join(",\n") +
    "\non conflict (id) do update set name = excluded.name, homepage = excluded.homepage, adapter = excluded.adapter, config = excluded.config, access_notes = excluded.access_notes;\n",
);

lines.push("-- Verified venue registry (coordinates checked against OpenStreetMap).");
lines.push("insert into venues (name, name_norm, address, locality, location, geo_status, geo_source, geo_confidence, geo_uncertainty_m, verified_at) values");
lines.push(
  KNOWN_VENUES.map((v) => `  (${q(v.name)}, '', ${q(v.address)}, ${q(v.locality)}, st_setsrid(st_makepoint(${v.lng}, ${v.lat}), 4326)::geography, 'verified', 'known_venue', 1, 0, now())`).join(",\n") +
    "\non conflict (name_norm, locality) do nothing;\n",
);
fs.writeFileSync("supabase/migrations/20261027000004_seed.sql", lines.join("\n"));
console.log("written");
